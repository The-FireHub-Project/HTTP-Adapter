namespace FireHub\Adapter\HTTP\Response;

use FireHub\Adapter\HTTP\ {
    Body, Response
};
use FireHub\Adapter\HTTP\Header\Content\Type as ContentType;
use FireHub\Adapter\HTTP\Response\Status\Standard;
use FireHub\Runtime;

/**
 * ### Represents a JSON HTTP response
 *
 * Encapsulates JSON content within an HTTP response.
 *
 * The response automatically assigns the application/json content type and defaults to HTTP 200 OK.
 * The character encoding is fixed to UTF-8 without an explicit charset parameter.
 *
 * JSON content may be supplied directly through an existing HTTP body or generated by serializing a PHP value.
 * When an existing body is supplied, the caller is responsible for ensuring that its content represents valid
 * UTF-8 encoded JSON.
 *
 * <code>
 * $response = new Json(new Body\Str('{"name":"FireHub"}'));
 *
 * $response = Json::fromValue([
 *     'name' => 'FireHub'
 * ]);
 *
 * $response->status(); // Standard::OK
 * </code>
 *
 * @since 1.0.0
 */
final readonly class Json extends Response {

    /**
     * ### Constructor
     * @since 1.0.0
     *
     * @uses \FireHub\Adapter\HTTP\Response\Headers::empty() To create an empty HTTP header collection.
     * @uses \FireHub\Adapter\HTTP\Header\Content\Type::parse() To construct the JSON content type.
     * @uses \FireHub\Adapter\HTTP\Message\Headers::withContentType() To assign the JSON content type.
     *
     * @param \FireHub\Adapter\HTTP\Body $body <p>
     * HTTP response body containing valid UTF-8 encoded JSON content.
     * </p>
     * @param \FireHub\Adapter\HTTP\Response\Status $status [optional] <p>
     * HTTP response status.
     * </p>
     * @param null|\FireHub\Adapter\HTTP\Response\Headers $headers [optional] <p>
     * Additional HTTP response headers.
     *
     * The Content-Type header is always replaced with application/json.
     * </p>
     *
     * @return void
     */
    public function __construct (Body $body, Status $status = Standard::OK, ?Headers $headers = null) {

        $headers ??= Headers::empty();

        parent::__construct(
            $status,
            $body,
            $headers->withContentType(
                ContentType::parse('application/json')
            )
        );

    }

    /**
     * ### Creates a JSON HTTP response from a PHP value
     *
     * Serializes the supplied PHP value into a JSON representation and encapsulates the resulting content
     * within a materialized HTTP message body.
     *
     * The supplied value is treated as PHP data rather than pre-serialized JSON content.
     *
     * <code>
     * $response = Json::fromValue([
     *     'id' => 1,
     *     'name' => 'FireHub'
     * ]);
     *
     * $created = Json::fromValue(
     *     ['id' => 2],
     *     Standard::CREATED
     * );
     *
     * $response->status(); // Standard::OK
     * $created->status(); // Standard::CREATED
     * </code>
     *
     * @since 1.0.0
     *
     * @uses \FireHub\Runtime\Json::encode() To serialize the supplied PHP value into JSON.
     * @uses \FireHub\Adapter\HTTP\Body\Str To encapsulate the serialized JSON content.
     *
     * @param mixed $value <p>
     * PHP value to serialize into a JSON representation.
     * </p>
     * @param \FireHub\Adapter\HTTP\Response\Status $status [optional] <p>
     * HTTP response status.
     * </p>
     * @param null|\FireHub\Adapter\HTTP\Response\Headers $headers [optional] <p>
     * Additional HTTP response headers.
     * </p>
     *
     * @return self JSON HTTP response containing the serialized PHP value.
     */
    public static function fromValue (mixed $value, Status $status = Standard::OK, ?Headers $headers = null):self {

        return new self(
            new Body\Str(
                Runtime\Json::encode($value)
            ),
            $status,
            $headers
        );

    }

}